void USpeedWheeledComponent::PreparePhysicsFrame(
	const float& DeltaTime, const float& SimTime)
{
	UpdateFrameState();
	// A test's initial state must be visible from the first movable frame, before any gameplay force can modify it.
	ApplyTestVelocity();
	UpdateSupportForceSleepState();
	// Handle forces that should be applied before the gameplay tick (e.g. gravity, damping, rest force)
	if (!DisableGravityThisFrame())
	{
		HandleGravity();
	}
	PreGameplayTick(DeltaTime, SimTime);

	// Handle gameplay forces (e.g. from player input or AI)
	GameplayTick(DeltaTime, SimTime);

	// Handle rest force after gameplay tick so that the component can be at rest at the end of the tick if it should be
	UpdateAutoRecoverState();
	// The exact-support lane owns normal/Coulomb reactions during CCD and
	// integration. A legacy host pre-cancellation would hide the actual load
	// (or cancel gravity while a face is still separated from its support).
	if (!GetStaticCollisionWorldForFrame()) HandleRestForce();
	HandlePhysicsAutoRecover();

	// Handle any necessary updates after the gameplay tick
	ApplyAccelKinematicsConstraint(DeltaTime);
	HandleTimers();
	PostGameplayTick(DeltaTime, SimTime);
}

void USpeedWheeledComponent::UpdateFrameState()
{
	HandleCountdownTimer();
	UpdateInputs();
	TagStateHistoryProxyRole();
	RecoverWheelState();
	if (CanMove() && !IsOnTheGround())
	{
		bCanonicalSupportStartupPoseConfirmed = false;
	}
	if (CanMove() && int32(NumFrame()) == SinceCanMoveFrame
		&& bCanonicalSupportStartupInitializationRequested)
	{
		bCanonicalSupportStartupInitializationRequested = false;
		bCanonicalSupportStartupPoseConfirmed = false;
		// Only an already stationary support is a startup point-fix candidate.
		// Callers opt in only when they authored an exact support pose. Full speed
		// checks still reject stale requests applied to a moving body.
		if (GetPhysCOMVelocity().Size() <= 0.01f
			&& GetPhysAngularVelocity().Size() <= 0.01f)
		{
			// RecoverWheelState runs after the countdown transition. Initialize the
			// support and its transient length here, after recovery but before gravity
			// and suspension consume the first movable frame.
			UpdateSubBodiesKinematics();
			for (auto& Wheel : WheelSubBodies)
			{
				if (Wheel)
				{
					Wheel->SweepSuspension(0.0f);
				}
			}
			bSimTimelineWasGrounded = IsOnTheGround();
			bCanonicalSupportStartupPoseConfirmed = bSimTimelineWasGrounded;
			if (bCanonicalSupportStartupPoseConfirmed)
			{
				ResetWheelTransientStateForCurrentPose(true);
			}
		}
	}
	if (CanMove() && CVarIAmSpeedDebugKinematics.GetValueOnAnyThread() != 0 && NumFrame() % 1 == 0)
	{
		const FVector Forward = GetPhysForwardVector();
		const FVector Right = GetPhysRightVector();
		const FVector Up = GetPhysUpVector();
		uint32 WheelMask = 0;
		for (const TObjectPtr<USWheelSubBody>& Wheel : WheelSubBodies)
		{
			if (Wheel && Wheel->IsOnGround() && Wheel->Idx() >= 0
				&& Wheel->Idx() < 32)
			{
				WheelMask |= 1u << Wheel->Idx();
			}
		}
		const FVector AngularVelocity = GetPhysAngularVelocity();
		const FVector LocalAngularVelocity(
			FVector::DotProduct(AngularVelocity, Forward),
			FVector::DotProduct(AngularVelocity, Right),
			FVector::DotProduct(AngularVelocity, Up));
		UE_LOG(SpeedPhysicsLog, Log,
			TEXT("[%s(%s)][UpdateFrameState] SinceCanMove=%d Wheels=%d Mask=0x%X COM=%s COMV=%s COMA=%s W=%s LocalW=%s Alpha=%s Forward=%s Right=%s Up=%s"),
			*GetOwner()->GetName(),
			*GetRole(),
			NbFramesSinceCanMove(),
			NumWheelsOnGround(),
			WheelMask,
			*GetPhysCOM().ToString(),
			*GetPhysCOMVelocity().ToString(),
			*GetPhysAccelerationAtPoint(GetPhysCOM()).ToString(),
			*AngularVelocity.ToString(),
			*LocalAngularVelocity.ToString(),
			*GetPhysAngularAcceleration().ToString(),
			*Forward.ToString(),
			*Right.ToString(),
			*Up.ToString());
	}
}
void USpeedWheeledComponent::UpdateNumFrame(const float& SimTime)
{
	const int32 CandidateFrame =
		FMath::RoundToInt32(double(SimTime) * double(EngineFPS)) + 1;

	const int32 PreviousFrame = int32(BaseGameState.NumFrame);

	if (PreviousFrame <= 0)
	{
		BaseGameState.NumFrame = CandidateFrame;
		return;
	}

	if (CandidateFrame < PreviousFrame)
	{
		constexpr int32 MinRollbackFramesForResim = 4;
		const int32 RollbackFrames = PreviousFrame - CandidateFrame;
		if (!HasAuthority() && RollbackFrames >= MinRollbackFramesForResim)
		{
			BaseGameState.NumFrame = CandidateFrame;
			return;
		}

		BaseGameState.NumFrame = PreviousFrame + 1;
		return;
	}

	if (CandidateFrame == PreviousFrame)
	{
		BaseGameState.NumFrame = PreviousFrame + 1;
		return;
	}

	if (CandidateFrame > PreviousFrame + 1)
	{
		BaseGameState.NumFrame = PreviousFrame + 1;
		return;
	}

	BaseGameState.NumFrame = CandidateFrame;
}

void USpeedWheeledComponent::ConsumeQueuedWheeledInputsForFrame(const int32 CurrentFrame)
{
	FScopeLock InputLock(&PendingWheeledInputMutex);
	for (int32 i = PendingWheeledInputCommands.Num() - 1; i >= 0; --i)
	{
		const FPendingWheeledInputCommand& Cmd = PendingWheeledInputCommands[i];

		if (Cmd.ActivationFrame <= CurrentFrame)
		{
			WheeledUserInput = Cmd.Input;
			if (Cmd.bBypassSlew)
			{
				WheeledPhysicalInput = WheeledUserInput;
				WheeledPhysicalInputBeforeSlew = WheeledPhysicalInput;
				LastWheeledInputSlewFrame = CurrentFrame;
				SyncWheeledPhysicalInputToState();
			}
			PendingWheeledInputCommands.RemoveAt(i);
		}
	}
}

void USpeedWheeledComponent::UpdateInputs()
{
	const int32 CurrentFrame = NumFrame();

	ConsumePendingLiveWheeledInputs();
	ConsumeQueuedWheeledInputsForFrame(CurrentFrame);

	UpdateWheeledPhysicalInputFromUser(false);
}

void USpeedWheeledComponent::ConsumePendingLiveWheeledInputs()
{
	const uint8 DirtyMask = PendingLiveWheeledInputMask.exchange(
		0, std::memory_order_acquire);
	if ((DirtyMask & LiveThrottleDirty) != 0)
	{
		WheeledUserInput.Throttle = PendingLiveThrottle.load(
			std::memory_order_relaxed);
	}
	if ((DirtyMask & LiveBrakeDirty) != 0)
	{
		WheeledUserInput.Brake = PendingLiveBrake.load(
			std::memory_order_relaxed);
	}
	if ((DirtyMask & LiveSteeringDirty) != 0)
	{
		WheeledUserInput.Steer = PendingLiveSteering.load(
			std::memory_order_relaxed);
	}
}

void USpeedWheeledComponent::UpdateWheeledPhysicalInputFromUser(bool bForce)
{
	const int32 CurrentFrame = NumFrame();

	if (!bForce && LastWheeledInputSlewFrame == CurrentFrame)
	{
		return;
	}

	LastWheeledInputSlewFrame = CurrentFrame;

	constexpr uint8 StepPerFrame = 16;

	WheeledPhysicalInput.Throttle = Speed::MoveTowardUInt8(
		WheeledPhysicalInput.Throttle,
		WheeledUserInput.Throttle,
		StepPerFrame
	);

	WheeledPhysicalInput.Brake = Speed::MoveTowardUInt8(
		WheeledPhysicalInput.Brake,
		WheeledUserInput.Brake,
		StepPerFrame
	);

	WheeledPhysicalInput.Steer = Speed::MoveTowardInt8(
		WheeledPhysicalInput.Steer,
		WheeledUserInput.Steer,
		StepPerFrame
	);
}

